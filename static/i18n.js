let i18nLocale = 'zh-CN';
const i18nListeners = [];

function canonicalLocale(value) {
  if (!value) return null;
  const v = String(value).trim();
  if (I18N_LOCALES.includes(v)) return v;
  const lower = v.toLowerCase().replace('_', '-');
  if (lower === 'zh' || lower.startsWith('zh-')) return 'zh-CN';
  if (lower === 'en' || lower.startsWith('en-')) return 'en';
  return null;
}

function resolveLocale({ choice, stored, browser } = {}) {
  return canonicalLocale(choice) || canonicalLocale(stored) || canonicalLocale(browser) || 'zh-CN';
}

function readStoredLocale() {
  try { return localStorage.getItem(I18N_STORAGE_KEY); } catch { return null; }
}

function writeStoredLocale(locale) {
  try { localStorage.setItem(I18N_STORAGE_KEY, locale); } catch { /* private mode */ }
}

function currentLocale() { return i18nLocale; }

function t(key, vars) {
  const table = i18nMessages[i18nLocale] || i18nMessages['zh-CN'];
  let text = table[key] ?? i18nMessages['zh-CN'][key] ?? key;
  if (vars) text = text.replace(/\{(\w+)\}/g, (_, name) => vars[name] == null ? '' : String(vars[name]));
  return text;
}

function onLocaleChange(fn) { i18nListeners.push(fn); }

function applyStaticTranslations() {
  if (typeof document === 'undefined') return;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n'), attr = el.getAttribute('data-i18n-attr');
    if (attr) el.setAttribute(attr, t(key));
    else el.textContent = t(key);
  });
  if (document.title !== undefined) document.title = t('meta.title');
  const group = document.getElementById('locale-switch');
  if (group) {
    group.setAttribute('aria-label', t('chrome.language'));
    group.querySelectorAll('[data-locale]').forEach(button => {
      button.setAttribute('aria-pressed', String(button.getAttribute('data-locale') === i18nLocale));
    });
  }
}

function applyLocale(locale, { persist = false, notify = true } = {}) {
  i18nLocale = locale;
  if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = locale;
  if (persist) writeStoredLocale(locale);
  applyStaticTranslations();
  if (notify) i18nListeners.forEach(fn => fn(locale));
}

function setLocale(locale) {
  const next = resolveLocale({ choice: locale });
  if (next === i18nLocale && readStoredLocale() === next) {
    applyStaticTranslations();
    return;
  }
  applyLocale(next, { persist: true, notify: true });
}

function bindLocaleSwitch() {
  const group = document.getElementById('locale-switch');
  if (!group || group.dataset.bound) return;
  group.dataset.bound = '1';
  group.addEventListener('click', event => {
    const button = event.target.closest('[data-locale]');
    if (!button) return;
    setLocale(button.getAttribute('data-locale'));
  });
}

function initI18n() {
  const locale = resolveLocale({ stored: readStoredLocale(), browser: typeof navigator !== 'undefined' ? navigator.language : '' });
  applyLocale(locale, { persist: false, notify: false });
  bindLocaleSwitch();
}

if (typeof document !== 'undefined') initI18n();
