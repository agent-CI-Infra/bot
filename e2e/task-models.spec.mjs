import { test, expect } from '@playwright/test';
import { mkdirSync, rmSync } from 'node:fs';
import { harness, setup, account, repository, testPassword } from '../test/helpers.mjs';

test('任务总览保存任务模型和规则，保留自定义任务并兼容旧地址与窄屏', async ({ page }) => {
  test.setTimeout(60000);
  const h = await harness(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  mkdirSync('.tmp/task-overview', { recursive: true });
  try {
    const { admin, password } = await setup(h), a = await account(admin);
    await repository(admin, a.id, '101');
    const create = async name => (await admin('/api/models', 'POST', { repository_id: '101', model_name: name, api_url: 'https://model.invalid/v1', api_key: testPassword() })).value.model;
    const defaultModel = await create('Project default'), review = await create('Review model'), obsolete = await create('Deleted model');
    await admin('/api/repositories/101/policy', 'PATCH', { model_id: defaultModel.id, task_models: { 'custom.science': obsolete.id } });
    await admin(`/api/models/${obsolete.id}`, 'DELETE', {});
    await page.goto(h.admin + '/#/projects/101/model');
    await page.getByLabel('用户名', { exact: true }).fill('administrator');
    await page.getByLabel('密码', { exact: true }).fill(password);
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await expect(page).toHaveURL(/#\/projects\/101\/tasks$/);
    await expect(page.getByRole('link', { name: '任务总览', exact: true })).toHaveAttribute('aria-current', 'page');
    for (const caption of ['使用的模型', '检视', '开发', '规则总览']) await expect(page.getByRole('link', { name: caption, exact: true })).toHaveCount(0);
    const card = kind => page.locator(`[data-task-kind="${kind}"]`);
    for (const [kind, title] of [['review.issue', '检视 Issue'], ['review.pr', '检视 PR'], ['development.issue', '开发 Issue'], ['development.pr', '跟进 bot PR'], ['release.observe', 'CI 观察'], ['release.notes', '发行说明']]) {
      await expect(card(kind)).toHaveCount(1);
      await expect(card(kind).getByRole('heading', { name: title, exact: true })).toBeVisible();
    }
    const custom = card('custom.science');
    await expect(custom.getByRole('combobox', { name: '任务模型', exact: true })).toHaveValue(obsolete.id);
    await expect(custom.locator('option:checked')).toContainText('模型不可用');
    const reviewCard = card('review.pr'), reviewModel = reviewCard.getByRole('combobox', { name: '任务模型', exact: true });
    const policy = async () => (await admin('/api/repositories/101')).value.policy;
    await expect(reviewModel).toHaveValue('');
    await reviewModel.selectOption(review.id);
    await page.route('**/api/repositories/101/policy', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"error":"storage_unavailable"}' }));
    await reviewCard.getByRole('button', { name: '保存模型', exact: true }).click();
    await expect(reviewCard.locator('.task-model-editor .view-error')).toContainText('storage_unavailable');
    await expect(reviewModel).toHaveValue(review.id);
    await reviewCard.screenshot({ path: '.tmp/task-overview/save-error.png' });
    await page.unroute('**/api/repositories/101/policy');
    await custom.getByRole('combobox', { name: '任务模型', exact: true }).selectOption(review.id);
    await custom.getByRole('button', { name: '保存模型', exact: true }).click();
    await expect.poll(async () => JSON.parse((await policy()).task_models)).toEqual({ 'custom.science': review.id });
    await expect(page.locator('.flash')).toHaveText('已保存custom.science的模型');
    await reviewModel.selectOption(review.id);
    await reviewCard.getByRole('button', { name: '保存模型', exact: true }).click();
    await expect.poll(async () => JSON.parse((await policy()).task_models)).toEqual({ 'review.pr': review.id, 'custom.science': review.id });
    await page.reload();
    await expect(reviewModel).toHaveValue(review.id);
    await reviewCard.getByRole('button', { name: '恢复继承', exact: true }).click();
    await expect.poll(async () => JSON.parse((await policy()).task_models)).toEqual({ 'custom.science': review.id });
    expect((await policy()).model_id).toBe(defaultModel.id);
    await page.reload();
    await expect(reviewModel).toHaveValue('');
    const rule = reviewCard.locator('[data-rule-path=".bot/rules/pr-review.md"]');
    await rule.getByRole('button', { name: '添加控制台覆盖', exact: true }).click();
    await rule.getByLabel('.bot/rules/pr-review.md 控制台覆盖', { exact: true }).fill('Console PR review rule');
    await rule.getByRole('button', { name: '保存', exact: true }).click();
    await expect(rule.locator('.flash')).toHaveText('已保存控制台覆盖');
    await expect.poll(async () => {
      const rules = (await admin('/api/repositories/101/rules')).value.rules;
      return rules.files.find(file => file.path === '.bot/rules/pr-review.md').layers.find(layer => layer.source === 'console')?.content;
    }).toBe('Console PR review rule');
    await custom.getByRole('button', { name: '移除自定义任务', exact: true }).click();
    await expect.poll(async () => JSON.parse((await policy()).task_models)).toEqual({});
    await expect(custom).toHaveCount(0);
    await expect(page.locator('.task-card[data-task-kind]')).toHaveCount(6);
    const defaultCard = page.locator('[data-overview-anchor="project-default-model"]');
    await defaultCard.getByRole('combobox', { name: '默认模型', exact: true }).selectOption(review.id);
    await defaultCard.getByRole('button', { name: '保存默认模型', exact: true }).click();
    await expect.poll(async () => (await policy()).model_id).toBe(review.id);
    await page.goto(h.admin + '/#/projects/101/review');
    await expect(page).toHaveURL(/#\/projects\/101\/tasks$/);
    await expect(card('review.issue')).toBeInViewport();
    await page.goto(h.admin + '/#/projects/101/development');
    await expect(page).toHaveURL(/#\/projects\/101\/tasks$/);
    await expect(card('development.issue')).toBeInViewport();
    await page.goto(h.admin + '/#/projects/101/rules');
    await expect(page).toHaveURL(/#\/projects\/101\/tasks$/);
    await expect(page.locator('[data-overview-anchor="rule-sources"]')).toBeInViewport();
    await page.reload();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await reviewCard.scrollIntoViewIfNeeded();
    await expect(reviewModel).toHaveValue('');
    const unclipped = () => page.locator('.task-card h3, .task-card button').evaluateAll(nodes => nodes.filter(node => node.scrollWidth > node.clientWidth + 1).map(node => node.textContent));
    expect(await unclipped()).toEqual([]);
    await page.screenshot({ path: '.tmp/task-overview/desktop.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await reviewCard.scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(await unclipped()).toEqual([]);
    await page.screenshot({ path: '.tmp/task-overview/mobile.png' });
    expect(errors).toEqual([]);
  } finally { await h.stop(); rmSync(h.directory, { recursive: true, force: true }); }
});
