import { createHash, randomBytes } from 'node:crypto';
import { ManagerError } from './docker.mjs';

export const PRECOMPILED_SCHEMA_VERSION = 1;
export const PRECOMPILED_REPO = 'department-bot-computer-precompiled';
const MIB = 1024 * 1024;
const OUTPUT_LIMIT = 32 * 1024;

// Environment names owned by the computer/runner or capable of dynamic code injection into the runner/shell.
export const reservedEnv = new Set([
  'PATH', 'HOME', 'TMPDIR', 'USER', 'SHELL', 'PWD', 'HOSTNAME',
  'NPM_CONFIG_PREFIX', 'UV_TOOL_DIR', 'UV_TOOL_BIN_DIR', 'PYTHONUSERBASE', 'PIP_USER', 'PREINSTALLED_DIR',
  'CARGO_HOME', 'GOPATH',
  'LD_PRELOAD', 'LD_LIBRARY_PATH', 'LD_AUDIT',
  'NODE_OPTIONS', 'NODE_PATH',
  'PYTHONSTARTUP', 'PYTHONHOME', 'PYTHONPATH',
  'BASH_ENV', 'ENV', 'ZDOTDIR', 'PROMPT_COMMAND',
]);

export function normalizePackages(packages) {
  return [...new Set((packages || []).filter(Boolean))].sort();
}

export function normalizeScript(script) {
  const normalized = String(script || '').replace(/\r\n/g, '\n');
  return normalized.trim() ? normalized : '';
}

export function normalizeEnv(env) {
  const out = {};
  for (const key of Object.keys(env || {}).sort()) out[key] = String(env[key]);
  return out;
}

export function computeImageKey({ baseImageId, packages = [], setupScript = '', env = {} }) {
  const payload = JSON.stringify({
    v: PRECOMPILED_SCHEMA_VERSION,
    base_image_id: String(baseImageId || ''),
    packages: normalizePackages(packages),
    setup_script: normalizeScript(setupScript),
    env: normalizeEnv(env),
  });
  return createHash('sha256').update(payload).digest('hex').slice(0, 16);
}

// Single-quoted POSIX shell assignment script; never interpolated into Dockerfile instructions.
export function shellEnvScript(env = {}) {
  const lines = ['# Generated by manager/precompiled-images.mjs'];
  for (const [key, value] of Object.entries(normalizeEnv(env))) {
    lines.push(`export ${key}='${String(value).replace(/'/g, `'\\''`)}'`);
  }
  return lines.join('\n') + '\n';
}

// Fixed Dockerfile template: apt packages run via validated package names only; setup_script ALWAYS runs as UID 10001
// from a tar-injected file, never as root and never interpolated into Dockerfile text.
export function generateLayerDockerfile({ fromImageId, packages = [], hasSetupScript = false }) {
  const lines = [`FROM ${fromImageId}`];
  const sortedPackages = normalizePackages(packages);
  if (sortedPackages.length) {
    lines.push(
      'USER 0',
      `RUN apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends -- ${sortedPackages.join(' ')} \\`,
      ' && rm -rf /var/lib/apt/lists/*',
      'USER 10001:10001',
    );
  }
  if (hasSetupScript) {
    // Set build-time install prefixes ONLY for this RUN so runtime agent installs still target writable HOME.
    lines.push(
      'USER 10001:10001',
      'COPY --chown=10001:10001 env.sh /tmp/bot-setup-env.sh',
      'COPY --chown=10001:10001 setup.sh /tmp/bot-setup.sh',
      "RUN HOME=/opt/preinstalled/home PREINSTALLED_DIR=/opt/preinstalled NPM_CONFIG_PREFIX=/opt/preinstalled/npm-global UV_TOOL_DIR=/opt/preinstalled/uv-tools UV_TOOL_BIN_DIR=/opt/preinstalled/bin PYTHONUSERBASE=/opt/preinstalled/python CARGO_HOME=/opt/preinstalled/cargo GOPATH=/opt/preinstalled/go /bin/sh -eu -c '. /tmp/bot-setup-env.sh && /bin/sh -eu /tmp/bot-setup.sh' && rm -f /tmp/bot-setup.sh /tmp/bot-setup-env.sh",
    );
  }
  lines.push(
    'USER 10001:10001',
    'WORKDIR /workspace',
    'CMD ["node", "/opt/runner/idle.mjs"]',
  );
  return lines.join('\n') + '\n';
}

function nowIso() { return new Date().toISOString(); }
function newBuildId() { return randomBytes(12).toString('hex'); }

/**
 * Serial (concurrency = 1), cancellable, two-level precompiled image builder with content-addressed caching,
 * single-flight deduplication, isolated build networking, streaming progress output, and reference-protected GC.
 */
export class PrecompiledImageBuilder {
  constructor({ docker, db, deployment, logFailure = () => {} }) {
    this.docker = docker;
    this.db = db;
    this.deployment = deployment;
    this.logFailure = logFailure;
    this.active = null;
    this.queue = [];
    this.jobsByKey = new Map();
    this.db.exec(`CREATE TABLE IF NOT EXISTS precompiled_images(
      image_key TEXT PRIMARY KEY,
      tag TEXT NOT NULL,
      kind TEXT NOT NULL,
      parent_image_id TEXT,
      base_image_id TEXT NOT NULL,
      spec_json TEXT NOT NULL,
      state TEXT NOT NULL,
      output TEXT,
      size_bytes INTEGER,
      last_used_at TEXT NOT NULL,
      created_at TEXT NOT NULL,
      finished_at TEXT
    )`);
  }

  buildNetworkName() { return `dbot-${this.deployment}-build-egress`; }
  buildNetworkLabels() { return { 'department.bot.deployment': this.deployment, 'department.bot.kind': 'build' }; }
  buildNetworkValid(network) {
    return !!network
      && !Object.entries(this.buildNetworkLabels()).some(([k, v]) => network.Labels?.[k] !== v)
      && network.Internal === false
      && network.Options?.['com.docker.network.bridge.enable_icc'] === 'false';
  }

  async ensureBuildNetwork() {
    const name = this.buildNetworkName();
    const existing = await this.docker.request('GET', `/networks/${name}`).catch(() => null);
    if (existing) {
      if (Object.entries(this.buildNetworkLabels()).some(([k, v]) => existing.Labels?.[k] !== v)) {
        throw new ManagerError('resource_ownership_mismatch', 403);
      }
      if (this.buildNetworkValid(existing)) return name;
      const removed = await this.docker.request('DELETE', `/networks/${name}`).then(() => true, () => false);
      if (!removed) throw new ManagerError('build_network_misconfigured', 503);
    }
    try {
      await this.docker.request('POST', '/networks/create', {
        Name: name,
        Driver: 'bridge',
        Internal: false,
        CheckDuplicate: true,
        Options: { 'com.docker.network.bridge.enable_icc': 'false' },
        Labels: this.buildNetworkLabels(),
      });
    } catch (error) {
      const created = await this.docker.request('GET', `/networks/${name}`).catch(() => null);
      if (!this.buildNetworkValid(created)) throw error;
    }
    return name;
  }

  async removeBuildNetwork() {
    const name = this.buildNetworkName();
    const existing = await this.docker.request('GET', `/networks/${name}`).catch(() => null);
    if (!existing || Object.entries(this.buildNetworkLabels()).some(([k, v]) => existing.Labels?.[k] !== v)) return;
    await this.docker.request('DELETE', `/networks/${name}`).catch(error => this.logFailure(`build egress network ${name} removal failed`, error));
  }

  upsertRow({ imageKey, tag, kind, parentImageId, baseImageId, spec, state, output = null, sizeBytes = null, finishedAt = null }) {
    const now = nowIso();
    this.db.prepare(`INSERT INTO precompiled_images(image_key,tag,kind,parent_image_id,base_image_id,spec_json,state,output,size_bytes,last_used_at,created_at,finished_at)
      VALUES(?,?,?,?,?,?,?,?,?,?,?,?)
      ON CONFLICT(image_key) DO UPDATE SET
        tag=excluded.tag,
        kind=excluded.kind,
        parent_image_id=excluded.parent_image_id,
        base_image_id=excluded.base_image_id,
        spec_json=excluded.spec_json,
        state=excluded.state,
        output=COALESCE(excluded.output, precompiled_images.output),
        size_bytes=COALESCE(excluded.size_bytes, precompiled_images.size_bytes),
        last_used_at=excluded.last_used_at,
        finished_at=excluded.finished_at`).run(
      imageKey, tag, kind, parentImageId ?? null, baseImageId, JSON.stringify(spec),
      state, output, sizeBytes, now, now, finishedAt,
    );
  }

  touchRow(imageKey, sizeBytes = null) {
    const now = nowIso();
    this.db.prepare('UPDATE precompiled_images SET last_used_at=?, size_bytes=COALESCE(?, size_bytes) WHERE image_key=?').run(now, sizeBytes, imageKey);
  }

  queuePosition(job) {
    if (this.active === job) return 0;
    const idx = this.queue.indexOf(job);
    return idx === -1 ? null : idx + 1;
  }

  snapshotJob(job, buildId) {
    return {
      build_id: buildId,
      image_key: job.imageKey,
      tag: job.tag,
      phase: job.kind,
      state: job.state,
      queue_position: this.queuePosition(job),
      started_at: job.startedAt,
      updated_at: job.updatedAt,
      finished_at: job.finishedAt,
      output: job.output || null,
      can_cancel: job.state === 'queued' || job.state === 'building',
    };
  }

  notifySubscribers(job) {
    for (const sub of job.subscribers) {
      if (sub.cancelled) continue;
      try { sub.onProgress?.(this.snapshotJob(job, sub.id)); } catch {}
    }
  }

  notifyQueuePositions() {
    for (const job of this.queue) this.notifySubscribers(job);
  }

  /**
   * Inspects whether a layer image already exists locally in Docker.
   */
  async findCachedLayer({ fromImageId, packages = [], setupScript = '', env = {} }) {
    const sortedPackages = normalizePackages(packages);
    const normalizedScript = normalizeScript(setupScript);
    if (!sortedPackages.length && !normalizedScript) return { noop: true, imageKey: null, tag: null, image: null };
    const buildEnv = normalizedScript ? normalizeEnv(env) : {};
    const imageKey = computeImageKey({ baseImageId: fromImageId, packages: sortedPackages, setupScript: normalizedScript, env: buildEnv });
    const tag = `${PRECOMPILED_REPO}:${imageKey}`;
    const image = await this.docker.request('GET', `/images/${encodeURIComponent(tag)}/json`);
    return { noop: false, imageKey, tag, image: image?.Id ? image : null };
  }

  /**
   * Ensures a single precompiled image layer (either global or project overlay).
   * Returns a handle with { build_id, image_key, tag, cached, promise, cancel }.
   */
  async ensureLayer({
    fromImageId,
    baseImageId,
    parentImageId = null,
    kind = 'global',
    packages = [],
    setupScript = '',
    env = {},
    resources = { cpus: 2, memory_mb: 4096 },
    egress = true,
    forceRebuild = false,
    onProgress = null,
  }) {
    const sortedPackages = normalizePackages(packages);
    const normalizedScript = normalizeScript(setupScript);
    if (!sortedPackages.length && !normalizedScript) {
      return {
        build_id: null,
        image_key: null,
        tag: null,
        cached: true,
        promise: Promise.resolve({ image: { Id: fromImageId }, image_key: null, tag: null, cached: true, output: null }),
        cancel: () => false,
      };
    }

    const buildEnv = normalizedScript ? normalizeEnv(env) : {};
    const imageKey = computeImageKey({ baseImageId: fromImageId, packages: sortedPackages, setupScript: normalizedScript, env: buildEnv });
    const tag = `${PRECOMPILED_REPO}:${imageKey}`;
    const spec = { packages: sortedPackages, has_setup_script: !!normalizedScript, env_keys: Object.keys(buildEnv) };

    if (!forceRebuild) {
      const existing = await this.docker.request('GET', `/images/${encodeURIComponent(tag)}/json`);
      if (existing?.Id) {
        const row = this.db.prepare('SELECT output FROM precompiled_images WHERE image_key=?').get(imageKey);
        if (row) this.touchRow(imageKey, existing.Size ?? null);
        else this.upsertRow({ imageKey, tag, kind, parentImageId, baseImageId, spec, state: 'ready', sizeBytes: existing.Size ?? null, finishedAt: nowIso() });
        const buildId = newBuildId();
        return {
          build_id: buildId,
          image_key: imageKey,
          tag,
          cached: true,
          promise: Promise.resolve({ image: existing, image_key: imageKey, tag, cached: true, output: row?.output ?? null }),
          cancel: () => false,
        };
      }
    }

    const subId = newBuildId();
    let resolveSub, rejectSub;
    const promise = new Promise((resolve, reject) => { resolveSub = resolve; rejectSub = reject; });
    const subscriber = { id: subId, resolve: resolveSub, reject: rejectSub, onProgress, cancelled: false };

    // Share an in-flight job ONLY when egress policy matches AND (if already building) the running job's resource
    // ceiling is at least as high as this caller's ceiling; queued jobs widen their ceiling before starting.
    const egressFlag = egress !== false;
    const jobKey = `${imageKey}:${egressFlag ? 'egress' : 'none'}`;
    const existingJob = !forceRebuild ? this.jobsByKey.get(jobKey) : null;
    const canShare = !!existingJob && (
      existingJob.state === 'queued'
      || (existingJob.state === 'building'
        && existingJob.resources.cpus >= resources.cpus
        && existingJob.resources.memory_mb >= resources.memory_mb)
    );
    let job = canShare ? existingJob : null;
    if (job) {
      job.subscribers.add(subscriber);
      if (job.state === 'queued') {
        job.resources = {
          cpus: Math.max(job.resources.cpus, resources.cpus),
          memory_mb: Math.max(job.resources.memory_mb, resources.memory_mb),
        };
      }
      try { onProgress?.(this.snapshotJob(job, subId)); } catch {}
    } else {
      job = {
        jobKey,
        imageKey,
        tag,
        kind,
        fromImageId,
        parentImageId,
        baseImageId,
        packages: sortedPackages,
        setupScript: normalizedScript,
        env: buildEnv,
        spec,
        resources: { cpus: resources.cpus, memory_mb: resources.memory_mb },
        egress: egressFlag,
        forceRebuild: !!forceRebuild,
        state: 'queued',
        output: '',
        startedAt: null,
        updatedAt: nowIso(),
        finishedAt: null,
        lastPersistAt: 0,
        abortController: new AbortController(),
        subscribers: new Set([subscriber]),
      };
      this.jobsByKey.set(jobKey, job);
      this.queue.push(job);
      this.upsertRow({ imageKey, tag, kind, parentImageId, baseImageId, spec, state: 'queued', output: '' });
      try { onProgress?.(this.snapshotJob(job, subId)); } catch {}
      this.drain();
    }

    const cancel = () => this.cancelSubscriber(job, subscriber);
    return { build_id: subId, image_key: imageKey, tag, cached: false, promise, cancel };
  }

  cancelSubscriber(job, subscriber) {
    if (subscriber.cancelled || !['queued', 'building'].includes(job.state)) return false;
    subscriber.cancelled = true;
    job.subscribers.delete(subscriber);
    const cancelledError = Object.assign(new ManagerError('image_build_cancelled', 409), { cancelled: true, output: job.output || null });
    try {
      subscriber.onProgress?.({
        ...this.snapshotJob(job, subscriber.id),
        state: 'cancelled',
        queue_position: null,
        finished_at: nowIso(),
        can_cancel: false,
      });
    } catch {}
    subscriber.reject(cancelledError);

    if (job.subscribers.size === 0) {
      if (job.state === 'queued') {
        const index = this.queue.indexOf(job);
        if (index !== -1) this.queue.splice(index, 1);
        if (this.jobsByKey.get(job.jobKey) === job) this.jobsByKey.delete(job.jobKey);
        job.state = 'cancelled';
        job.finishedAt = nowIso();
        job.updatedAt = job.finishedAt;
        this.upsertRow({
          imageKey: job.imageKey, tag: job.tag, kind: job.kind, parentImageId: job.parentImageId,
          baseImageId: job.baseImageId, spec: job.spec, state: 'cancelled', output: job.output || null, finishedAt: job.finishedAt,
        });
        this.notifyQueuePositions();
      } else if (job.state === 'building') {
        job.state = 'cancelling';
        job.updatedAt = nowIso();
        job.abortController.abort();
      }
    }
    return true;
  }

  drain() {
    if (this.active || !this.queue.length) return;
    const job = this.queue.shift();
    this.active = job;
    this.notifyQueuePositions();
    void this.runJob(job).finally(() => {
      if (this.active === job) this.active = null;
      if (this.jobsByKey.get(job.jobKey) === job) this.jobsByKey.delete(job.jobKey);
      this.drain();
    });
  }

  async runJob(job) {
    if (job.subscribers.size === 0 || job.abortController.signal.aborted) {
      job.state = 'cancelled';
      job.finishedAt = nowIso();
      job.updatedAt = job.finishedAt;
      this.upsertRow({
        imageKey: job.imageKey, tag: job.tag, kind: job.kind, parentImageId: job.parentImageId,
        baseImageId: job.baseImageId, spec: job.spec, state: 'cancelled', output: job.output || null, finishedAt: job.finishedAt,
      });
      return;
    }

    job.state = 'building';
    job.startedAt = nowIso();
    job.updatedAt = job.startedAt;

    // Re-check local cache once at the front of the queue: if an earlier job with a lower ceiling just built this
    // identical content-addressed tag, reuse it without rebuilding.
    if (!job.forceRebuild) {
      const existing = await this.docker.request('GET', `/images/${encodeURIComponent(job.tag)}/json`).catch(() => null);
      if (existing?.Id) {
        const finished = nowIso();
        job.state = 'ready';
        job.finishedAt = finished;
        job.updatedAt = finished;
        this.touchRow(job.imageKey, existing.Size ?? null);
        this.notifySubscribers(job);
        for (const sub of [...job.subscribers]) {
          if (!sub.cancelled) sub.resolve({ image: existing, image_key: job.imageKey, tag: job.tag, cached: true, output: null });
        }
        job.subscribers.clear();
        return;
      }
    }

    this.upsertRow({
      imageKey: job.imageKey, tag: job.tag, kind: job.kind, parentImageId: job.parentImageId,
      baseImageId: job.baseImageId, spec: job.spec, state: 'building', output: '',
    });
    this.notifySubscribers(job);

    const hasSetupScript = !!job.setupScript;
    const dockerfile = generateLayerDockerfile({ fromImageId: job.fromImageId, packages: job.packages, hasSetupScript });
    const files = hasSetupScript ? { 'env.sh': shellEnvScript(job.env), 'setup.sh': job.setupScript + '\n' } : {};
    const labels = {
      'department.bot.deployment': this.deployment,
      'department.bot.kind': 'precompiled-image',
      'department.bot.image_key': job.imageKey,
      'department.bot.image_layer': job.kind,
      'department.bot.base_image_id': job.baseImageId,
    };

    try {
      const networkmode = job.egress ? await this.ensureBuildNetwork() : 'none';
      if (job.abortController.signal.aborted) throw Object.assign(new ManagerError('image_build_cancelled', 409), { cancelled: true, output: job.output });
      const memory = Math.round(job.resources.memory_mb * MIB);
      const cpuquota = Math.round(job.resources.cpus * 100000);
      const output = await this.docker.build(job.tag, dockerfile, labels, {
        timeout: 0,
        files,
        memory,
        memswap: memory,
        cpuquota,
        cpuperiod: 100000,
        networkmode,
        signal: job.abortController.signal,
        onOutput: (_chunk, rolling) => {
          job.output = rolling.slice(-OUTPUT_LIMIT);
          job.updatedAt = nowIso();
          const now = Date.now();
          if (now - job.lastPersistAt >= 1000) {
            job.lastPersistAt = now;
            this.db.prepare('UPDATE precompiled_images SET output=?, last_used_at=? WHERE image_key=?').run(job.output, job.updatedAt, job.imageKey);
          }
          this.notifySubscribers(job);
        },
      });
      if (job.abortController.signal.aborted) throw Object.assign(new ManagerError('image_build_cancelled', 409), { cancelled: true, output: output || job.output });
      const image = await this.docker.request('GET', `/images/${encodeURIComponent(job.tag)}/json`);
      if (!image?.Id) throw Object.assign(new ManagerError('image_build_failed', 409), { output: output || job.output });

      job.output = (output || job.output || '').slice(-OUTPUT_LIMIT);
      job.state = 'ready';
      job.finishedAt = nowIso();
      job.updatedAt = job.finishedAt;
      this.upsertRow({
        imageKey: job.imageKey, tag: job.tag, kind: job.kind, parentImageId: job.parentImageId,
        baseImageId: job.baseImageId, spec: job.spec, state: 'ready', output: job.output, sizeBytes: image.Size ?? null, finishedAt: job.finishedAt,
      });
      this.notifySubscribers(job);
      for (const sub of [...job.subscribers]) {
        if (!sub.cancelled) sub.resolve({ image, image_key: job.imageKey, tag: job.tag, cached: false, output: job.output });
      }
      job.subscribers.clear();
    } catch (error) {
      const cancelled = !!(error?.cancelled || job.abortController.signal.aborted);
      if (error?.output) job.output = String(error.output).slice(-OUTPUT_LIMIT);
      job.state = cancelled ? 'cancelled' : 'failed';
      job.finishedAt = nowIso();
      job.updatedAt = job.finishedAt;
      this.upsertRow({
        imageKey: job.imageKey, tag: job.tag, kind: job.kind, parentImageId: job.parentImageId,
        baseImageId: job.baseImageId, spec: job.spec, state: job.state, output: job.output || null, finishedAt: job.finishedAt,
      });
      this.notifySubscribers(job);
      const err = cancelled
        ? Object.assign(new ManagerError('image_build_cancelled', 409), { cancelled: true, output: job.output || null })
        : error;
      for (const sub of [...job.subscribers]) {
        if (!sub.cancelled) sub.reject(err);
      }
      job.subscribers.clear();
    }
  }

  /**
   * Computes whether a two-level (global + optional project overlay) image is already cached locally.
   */
  async checkLayeredCache({ approvedImage, globalSpec, projectSpec = null }) {
    const globalPkgs = normalizePackages(globalSpec?.packages);
    const globalScript = normalizeScript(globalSpec?.setup_script);
    const globalEnv = globalSpec?.env || {};
    let level1Image = approvedImage;
    let level1Cached = true;
    let level1Key = null;
    let level1Tag = null;

    if (globalPkgs.length || globalScript) {
      const found = await this.findCachedLayer({ fromImageId: approvedImage.Id, packages: globalPkgs, setupScript: globalScript, env: globalEnv });
      level1Key = found.imageKey;
      level1Tag = found.tag;
      if (!found.image) return { cached: false, image: null, globalImage: null, image_key: level1Key, tag: level1Tag };
      level1Image = found.image;
    }

    if (!projectSpec) {
      return { cached: level1Cached, image: level1Image, globalImage: level1Image, image_key: level1Key, tag: level1Tag };
    }

    const globalSet = new Set(globalPkgs);
    const deltaPkgs = normalizePackages(projectSpec.packages).filter(pkg => !globalSet.has(pkg));
    const projectScript = normalizeScript(projectSpec.setup_script);
    if (!deltaPkgs.length && !projectScript) {
      return { cached: true, image: level1Image, globalImage: level1Image, image_key: level1Key, tag: level1Tag };
    }
    const effectiveEnv = { ...globalEnv, ...(projectSpec.env || {}) };
    const found2 = await this.findCachedLayer({ fromImageId: level1Image.Id, packages: deltaPkgs, setupScript: projectScript, env: effectiveEnv });
    if (!found2.image) return { cached: false, image: null, globalImage: level1Image, image_key: found2.imageKey, tag: found2.tag };
    return { cached: true, image: found2.image, globalImage: level1Image, image_key: found2.imageKey, tag: found2.tag };
  }

  /**
   * Two-level additive build:
   * - Level 1 (global): global.packages + global.setup_script on top of approvedImage
   * - Level 2 (project): project delta packages + project.setup_script on top of Level 1 image
   */
  startLayered({
    approvedImage,
    globalSpec,
    projectSpec = null,
    resources = { cpus: 2, memory_mb: 4096 },
    egress = true,
    forceRebuild = false,
    forceRebuildGlobal = false,
    onProgress = null,
  }) {
    let activeHandle = null;
    let cancelled = false;
    const buildId = newBuildId();

    const cancel = () => {
      if (cancelled) return false;
      cancelled = true;
      return activeHandle ? activeHandle.cancel() : true;
    };

    const promise = (async () => {
      const globalPkgs = normalizePackages(globalSpec?.packages);
      const globalScript = normalizeScript(globalSpec?.setup_script);
      const globalEnv = globalSpec?.env || {};
      let level1Image = approvedImage;
      let level1Result = { image: approvedImage, image_key: null, tag: null, cached: true, output: null };

      if (globalPkgs.length || globalScript) {
        activeHandle = await this.ensureLayer({
          fromImageId: approvedImage.Id,
          baseImageId: approvedImage.Id,
          parentImageId: null,
          kind: 'global',
          packages: globalPkgs,
          setupScript: globalScript,
          env: globalEnv,
          resources,
          egress,
          forceRebuild: forceRebuildGlobal,
          onProgress: state => onProgress?.({ ...state, build_id: buildId }),
        });
        if (cancelled) {
          activeHandle.cancel();
          throw Object.assign(new ManagerError('image_build_cancelled', 409), { cancelled: true });
        }
        level1Result = await activeHandle.promise;
        level1Image = level1Result.image;
      }

      if (!projectSpec) return { ...level1Result, globalImage: level1Image };

      const globalSet = new Set(globalPkgs);
      const deltaPkgs = normalizePackages(projectSpec.packages).filter(pkg => !globalSet.has(pkg));
      const projectScript = normalizeScript(projectSpec.setup_script);
      if (!deltaPkgs.length && !projectScript) {
        return { ...level1Result, globalImage: level1Image };
      }

      if (cancelled) throw Object.assign(new ManagerError('image_build_cancelled', 409), { cancelled: true });
      const effectiveEnv = { ...globalEnv, ...(projectSpec.env || {}) };
      activeHandle = await this.ensureLayer({
        fromImageId: level1Image.Id,
        baseImageId: approvedImage.Id,
        parentImageId: level1Image.Id,
        kind: 'project',
        packages: deltaPkgs,
        setupScript: projectScript,
        env: effectiveEnv,
        resources,
        egress,
        forceRebuild,
        onProgress: state => onProgress?.({ ...state, build_id: buildId }),
      });
      if (cancelled) {
        activeHandle.cancel();
        throw Object.assign(new ManagerError('image_build_cancelled', 409), { cancelled: true });
      }
      const level2Result = await activeHandle.promise;
      return { ...level2Result, globalImage: level1Image };
    })();

    return { build_id: buildId, promise, cancel };
  }

  reconcileInterrupted() {
    const activeKeys = new Set([...this.jobsByKey.values()].map(job => job.imageKey));
    const stale = this.db.prepare("SELECT image_key, output FROM precompiled_images WHERE state IN ('queued','building','cancelling')").all();
    const now = nowIso();
    let count = 0;
    for (const row of stale) {
      if (activeKeys.has(row.image_key)) continue;
      const nextOutput = `${row.output ? row.output + '\n' : ''}[interrupted by manager restart]`.slice(-OUTPUT_LIMIT);
      this.db.prepare("UPDATE precompiled_images SET state='failed', output=?, finished_at=?, last_used_at=? WHERE image_key=?").run(nextOutput, now, now, row.image_key);
      count++;
    }
    return count;
  }

  async listImages({ protectedImageIds = new Set(), protectedTags = new Set() } = {}) {
    const rows = this.db.prepare('SELECT * FROM precompiled_images ORDER BY last_used_at DESC').all();
    const tagToId = new Map();
    for (const row of rows) {
      if (row.state === 'ready') {
        const info = await this.docker.request('GET', `/images/${encodeURIComponent(row.tag)}/json`).catch(() => null);
        if (info?.Id) tagToId.set(row.tag, info.Id);
      }
    }
    const idToKey = new Map();
    for (const row of rows) {
      const id = tagToId.get(row.tag);
      if (id) idToKey.set(id, row.image_key);
    }
    const protectedKeys = new Set();
    const markKey = key => {
      if (!key || protectedKeys.has(key)) return;
      protectedKeys.add(key);
      const row = rows.find(r => r.image_key === key);
      if (row?.parent_image_id && idToKey.has(row.parent_image_id)) markKey(idToKey.get(row.parent_image_id));
    };
    // Walk active and queued jobs AND their parent layers so manual prune never removes the parent of a queued build.
    for (const job of this.jobsByKey.values()) {
      markKey(job.imageKey);
      if (job.parentImageId && idToKey.has(job.parentImageId)) markKey(idToKey.get(job.parentImageId));
      if (job.fromImageId && idToKey.has(job.fromImageId)) markKey(idToKey.get(job.fromImageId));
    }
    for (const row of rows) {
      const id = tagToId.get(row.tag);
      if (protectedTags.has(row.tag) || (id && protectedImageIds.has(id))) markKey(row.image_key);
    }
    const safeSpec = raw => { try { return JSON.parse(raw || '{}'); } catch { return {}; } };

    return {
      queue_length: this.queue.length,
      active_build: this.active ? { image_key: this.active.imageKey, tag: this.active.tag, kind: this.active.kind, started_at: this.active.startedAt } : null,
      images: rows.map(row => ({
        image_key: row.image_key,
        tag: row.tag,
        kind: row.kind,
        parent_image_id: row.parent_image_id,
        base_image_id: row.base_image_id,
        spec: safeSpec(row.spec_json),
        state: row.state,
        size_bytes: row.size_bytes ?? null,
        present: tagToId.has(row.tag),
        protected: protectedKeys.has(row.image_key),
        last_used_at: row.last_used_at,
        created_at: row.created_at,
        finished_at: row.finished_at,
      })),
    };
  }

  async prune({ protectedImageIds = new Set(), protectedTags = new Set(), keepUnreferenced = 5, maxAgeDays = 7, force = false } = {}) {
    const listed = await this.listImages({ protectedImageIds, protectedTags });
    const unreferenced = listed.images.filter(img => !img.protected);
    const cutoff = Date.now() - maxAgeDays * 86400_000;
    const toRemove = force
      ? unreferenced
      : unreferenced.filter((img, idx) => idx >= keepUnreferenced && Date.parse(img.last_used_at) < cutoff);

    const removed = [];
    for (const img of toRemove) {
      try {
        if (img.present) await this.docker.request('DELETE', `/images/${encodeURIComponent(img.tag)}`);
        this.db.prepare('DELETE FROM precompiled_images WHERE image_key=?').run(img.image_key);
        removed.push({ image_key: img.image_key, tag: img.tag, size_bytes: img.size_bytes });
      } catch (error) {
        this.logFailure(`pruning precompiled image ${img.tag} failed`, error);
      }
    }
    return { removed, kept: listed.images.length - removed.length };
  }

  async shutdown() {
    for (const job of [...this.queue]) {
      for (const sub of [...job.subscribers]) this.cancelSubscriber(job, sub);
    }
    if (this.active) {
      for (const sub of [...this.active.subscribers]) this.cancelSubscriber(this.active, sub);
    }
    await this.removeBuildNetwork();
  }
}
